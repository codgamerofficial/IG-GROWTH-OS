function createCapabilities(flags: Partial<Record<CapabilityFlag, boolean>>): Record<CapabilityFlag, boolean> {
  const allFlags: CapabilityFlag[] = [
    'TEXT_INPUT',
    'TEXT_OUTPUT',
    'IMAGE_INPUT',
    'IMAGE_OUTPUT',
    'VIDEO_INPUT',
    'VIDEO_OUTPUT',
    'AUDIO_INPUT',
    'AUDIO_OUTPUT',
    'TRANSCRIPTION',
    'SPEECH_GENERATION',
    'MUSIC_GENERATION',
    'EMBEDDINGS',
    'RERANKING',
    'TOOL_CALLING',
    'STRUCTURED_OUTPUT',
    'STREAMING',
    'LONG_CONTEXT',
    'CODE_GENERATION',
    'REASONING',
  ];

  const result: Record<string, boolean> = {};
  for (const f of allFlags) {
    result[f] = Boolean(flags[f]);
  }
  return result as Record<CapabilityFlag, boolean>;
}

